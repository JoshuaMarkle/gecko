#!/usr/bin/env python3
"""layout-ranking.md → layout-ranking.tex → layout-ranking.pdf (gecko-paper.cls, single column).
Usage: python3 -I docs/papers/layout-ranking/build.py   (needs pandoc and XeLaTeX; run figures.py first)
Edit the .md; the .tex is generated.
"""
import re, subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPERS = HERE.parent
MD = HERE / 'layout-ranking.md'
LUA = PAPERS / 'drafts' / 'links-to-text.lua'
BUILD = PAPERS / 'templates' / 'build_pdf.sh'

MATH = {'≤': r'$\leq$', '≥': r'$\geq$', '→': r'$\to$', '≈': r'$\approx$', '×': r'$\times$', '↔': r'$\leftrightarrow$',
        '…': r'\ldots{}', '±': r'$\pm$', '−': r'$-$', 'σ': r'$\sigma$', '†': r'\textsuperscript{\dag}'}

def pandoc(md):
    return subprocess.run(['pandoc', '-f', 'markdown-auto_identifiers', '-t', 'latex', '--columns=400', '--lua-filter', str(LUA)],
                          input=md, capture_output=True, text=True, check=True).stdout

def esc(s):
    return re.sub(r'([&%$#_{}])', r'\\\1', s)

def figures(tex):
    # pandoc's figure block → full-width image + caption (assets/<name>.pdf)
    pat = re.compile(r'\\begin\{figure\}.*?\\includegraphics(?:\[[^\]]*\])?\{assets/([^}]+)\.pdf\}.*?\\caption\{(.*?)\}\s*(?:\\label\{[^}]*\})?\s*\\end\{figure\}', re.S)
    return pat.sub(lambda m: '\\paperfigure{%s}{%s}' % (m[1], m[2]), tex)

text = MD.read_text()
title = re.search(r'^# (.+)$', text, re.M)[1]
status = re.sub(r'\s+', ' ', re.search(r'^\*(.+?)\*\s*$', text, re.M | re.S)[1])
parts = re.split(r'^## ', text, flags=re.M)[1:]
abstract = next(p.partition('\n')[2] for p in parts if p.lower().startswith('abstract'))
body = '\n'.join('# ' + p for p in parts if not p.lower().startswith('abstract'))
main, _, sub = title.partition(': ')
body_tex = figures(pandoc(body)).replace('\\tightlist', '\\setlength{\\itemsep}{1pt}\\setlength{\\parskip}{0pt}')
tex = rf"""% Generated by build.py from {MD.name}. Edit the .md, not this file.
\documentclass{{gecko-paper}}
\usepackage{{longtable,array,calc}}
\providecommand{{\pandocbounded}}[1]{{#1}}
\newcounter{{none}}
\setlength{{\LTleft}}{{0pt}}\setlength{{\LTright}}{{0pt plus 1fill}}
\renewcommand{{\paperfigure}}[2]{{\par\addvspace{{9pt}}\noindent\begin{{minipage}}{{\linewidth}}\centering
  \includegraphics[width=.92\linewidth]{{assets/#1.pdf}}\captionof{{figure}}{{#2}}\end{{minipage}}\par\addvspace{{9pt}}}}
\paperfooter{{Joshua Markle · University of Virginia}}{{GECKO layout ranking}}
\paperpdfinfo{{{esc(title)}}}{{Joshua Markle}}{{Experiment report}}
\papertitle{{{esc(main)}}}
\papersubtitle{{{esc(sub[0].upper() + sub[1:])}}}
\paperauthor{{Joshua Markle}}
\paperaffil{{University of Virginia · October 2026}}
\papernotice{{{pandoc(status).strip()}}}
\sloppy
\begin{{document}}
\makepapertitle
\begin{{paperabstract}}
{pandoc(abstract)}
\end{{paperabstract}}
\raggedright
{{\small
{body_tex}
}}
\end{{document}}
"""
def glyphs(t):
    t = t.replace('---', '—').replace('--', '–').replace('``', '“').replace("''", '”')
    for k, v in MATH.items():
        t = t.replace(k, v)
    return t
# leave verbatim blocks (shell commands) untouched
tex = ''.join(p if p.startswith('\\begin{verbatim}') else glyphs(p)
              for p in re.split(r'(\\begin\{verbatim\}.*?\\end\{verbatim\})', tex, flags=re.S))
out = HERE / 'layout-ranking.tex'
out.write_text(tex)
subprocess.run([str(BUILD), str(out)], check=True)
