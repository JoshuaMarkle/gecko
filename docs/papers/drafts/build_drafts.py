#!/usr/bin/env python3
"""Turn each drafts/*.md (and later/*.md) into <name>.tex and <name>.pdf with gecko-paper.cls.
Usage: python3 -I docs/papers/drafts/build_drafts.py [file.md ...]   (default: all drafts)
Needs pandoc and XeLaTeX. Draft format: '# Title', an italic status paragraph, '## Abstract...',
then '##' sections. Keep prose in the .md; the .tex/.pdf are generated.
"""
import re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUILD = HERE.parent / 'templates' / 'build_pdf.sh'
LUA = HERE / 'links-to-text.lua'

def pandoc(md, extra=()):
    return subprocess.run(['pandoc', '-f', 'markdown-auto_identifiers', '-t', 'latex', '--lua-filter', str(LUA),
                           *extra], input=md, capture_output=True, text=True, check=True).stdout

MATH = {'≤': r'$\leq$', '≥': r'$\geq$', '→': r'$\to$', '≈': r'$\approx$', '×': r'$\times$', '≫': r'$\gg$',
        '…': r'\ldots{}', '⇒': r'$\Rightarrow$', '≠': r'$\neq$', '±': r'$\pm$'}
def glyphs(s):
    s = s.replace('---', '—').replace('--', '–').replace('``', '“').replace("''", '”')
    for k, v in MATH.items():
        s = s.replace(k, v)
    return s

def tex_escape(s):
    return re.sub(r'([&%$#_{}])', r'\\\1', s)

def convert(path):
    text = path.read_text()
    title = re.search(r'^# (.+)$', text, re.M)[1]
    status = re.search(r'^\*(.+?)\*\s*$', text, re.M | re.S)
    status = re.sub(r'\s+', ' ', status[1]) if status else ''
    status = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', status).replace('Skeleton. ', '')
    parts = re.split(r'^## ', text, flags=re.M)[1:]
    abstract, rest = '', []
    for p in parts:
        head, _, body = p.partition('\n')
        if head.lower().startswith('abstract'):
            abstract = body.strip()
        else:
            rest.append('# ' + head + '\n' + body)
    status_tex = pandoc(status).strip()
    main, _, sub = title.partition(': ')
    body_tex = pandoc('\n'.join(rest))
    abs_tex = pandoc(abstract)
    body_tex = body_tex.replace('\\tightlist', '\\setlength{\\itemsep}{1pt}\\setlength{\\parskip}{0pt}')
    # Title: split on ': ' or ' for ' only if long, for balanced lines.
    tex = rf"""% Generated by build_drafts.py from {path.name}. Edit the .md, not this file.
\documentclass{{gecko-paper}}
\paperfooter{{Joshua Markle · University of Virginia}}{{GECKO draft}}
\paperpdfinfo{{{tex_escape(title)}}}{{Joshua Markle}}{{Working draft}}
\papertitle{{{tex_escape(main)}}}
\papersubtitle{{{tex_escape(sub)}}}
\paperauthor{{Joshua Markle}}
\paperaffil{{University of Virginia · October 2026}}
\papernotice{{Working draft skeleton · no results yet · bracketed TODOs are placeholders\\ {status_tex}}}
\sloppy
\begin{{document}}
\makepapertitle
\begin{{paperabstract}}
{abs_tex}
\end{{paperabstract}}
\begin{{paperbody}}
{body_tex}
\end{{paperbody}}
\end{{document}}
"""
    out = path.with_suffix('.tex')
    out.write_text(glyphs(tex))
    subprocess.run([str(BUILD), str(out)], check=True)

files = [Path(a).resolve() for a in sys.argv[1:]] or sorted(HERE.glob('*.md')) + sorted((HERE / 'later').glob('*.md'))
for f in files:
    convert(f)
