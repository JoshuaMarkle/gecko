"""Pick source files for GECKO's code/markdown corpora; writes <component>.list (one path per
line). Rules: newest version per crate/package, authored files only (no generated, minified,
vendored-test or table files), a byte cap per package so no single package dominates."""
import os, re, glob, sys
HOME = os.path.expanduser("~")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
GEN = re.compile(rb"generated|do not edit|autogenerated|@generated", re.I)

def authored(p, max_bytes=150_000):
    try:
        st = os.stat(p)
        if st.st_size == 0 or st.st_size > max_bytes:
            return False
        with open(p, "rb") as f:
            b = f.read()
    except OSError:
        return False
    if GEN.search(b[:2000]):
        return False
    lines = b.count(b"\n") + 1
    if len(b) / lines > 120:  # minified or data
        return False
    try:
        b.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True

def capped(files, cap):
    out, tot = [], 0
    for f in sorted(files):
        if not authored(f):
            continue
        n = os.path.getsize(f)
        if tot + n > cap:
            continue
        out.append(f); tot += n
    return out

def vkey(v):
    return [int(x) if x.isdigit() else -1 for x in re.split(r"[.+-]", v)]

def latest_crates():
    best = {}
    for d in glob.glob(f"{HOME}/.cargo/registry/src/*/*/"):
        m = re.match(r"(.+)-(\d+\.\d+\.\d+.*)$", os.path.basename(d.rstrip("/")))
        if not m:
            continue
        name, ver = m.groups()
        if name not in best or vkey(ver) > vkey(best[name][0]):
            best[name] = (ver, d)
    return {k: v[1] for k, v in best.items()}

SKIP_CRATES = re.compile(r"^(windows.*|linux-raw-sys|libc|web-sys|js-sys|unicode-.*|encoding_rs|icu_.*|.*_data|zerovec.*|tinystr|idna.*|winapi.*|wasm-bindgen.*|rustix|nix|core-foundation.*|objc.*)$")

def walk(root, exts, skip_dirs=()):
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if not d.startswith(".") and d not in skip_dirs]
        for f in fns:
            if any(f.endswith(e) for e in exts):
                yield os.path.join(dp, f)

lists = {}
crates = latest_crates()
lists["code-rust"] = [f for n, d in sorted(crates.items()) if not SKIP_CRATES.match(n) and os.path.isdir(d + "src")
                      for f in capped(walk(d + "src", [".rs"], ("tests", "benches", "unicode_tables", "tables")), 120_000)]
C_SKIP = ("tests", "test", "fuzz", "examples", "contrib", "doc")
lists["code-c"] = [f for n in ["zstd-sys", "lzma-sys", "bzip2-sys", "ring"] if n in crates
                   for f in capped(walk(crates[n], [".c", ".h"], C_SKIP), 1_500_000)]
py = "/usr/lib/python3.14"
pkgs = {}
for f in walk(py, [".py"], ("test", "tests", "idle_test", "encodings", "pydoc_data", "site-packages", "__pycache__", "lib2to3", "turtledemo", "idlelib")):
    rel = os.path.relpath(f, py).split(os.sep)
    pkgs.setdefault(rel[0] if len(rel) > 1 else f, []).append(f)
lists["code-python"] = [f for k in sorted(pkgs) for f in capped(pkgs[k], 200_000)]
nm = set()
for d in glob.glob(f"{HOME}/projects/*/web/node_modules") + glob.glob(f"{HOME}/projects/*/node_modules"):
    for p in glob.glob(d + "/*/") + glob.glob(d + "/@*/*/"):
        if os.path.isdir(p + "src"):
            nm.add(os.path.realpath(p))
seen = set(); js = []
for p in sorted(nm):
    name = os.path.basename(p)
    if name in seen:
        continue
    seen.add(name)
    files = [f for f in walk(p + "/src", [".ts", ".tsx", ".js", ".jsx", ".mjs"], ("__tests__", "test", "tests", "dist", "build", "cjs", "esm", "umd", "vendor"))
             if not f.endswith(".d.ts") and ".min." not in f and ".test." not in f and ".spec." not in f]
    js += capped(files, 120_000)
lists["code-js"] = js
sh = []
for f in glob.glob("/usr/bin/*") + glob.glob(f"{HOME}/.cache/yay/*/PKGBUILD") + list(walk("/usr/share/makepkg", [".sh"])) + list(walk(f"{HOME}/.cargo/registry/src", [".sh"])):
    try:
        if os.path.isfile(f) and not os.path.islink(f):
            with open(f, "rb") as fh:
                head = fh.read(64)
            if f.endswith((".sh", "PKGBUILD")) or re.match(rb"#!\s*/(usr/)?bin/(env )?(ba|z|da)?sh\b", head):
                sh.append(f)
    except OSError:
        pass
lists["code-shell"] = capped(sh, 3_000_000)
rt = "/usr/share/nvim/runtime"
lists["code-lua"] = capped([f for f in walk(rt, [".lua", ".vim"], ("doc", "syntax", "colors", "spell", "tutor"))], 3_000_000)
md = []
for n, d in sorted(crates.items()):
    md += capped([f for f in walk(d, [".md"], ("target",)) if not re.search(r"(CHANGE|HISTORY|LICENSE|CODE_OF|RELEASE)", os.path.basename(f), re.I)], 60_000)
for p in sorted(nm):
    md += capped([f for f in glob.glob(p + "/*.md") + glob.glob(p + "/docs/**/*.md", recursive=True)
                  if not re.search(r"(CHANGE|HISTORY|LICENSE|CODE_OF|RELEASE)", os.path.basename(f), re.I)], 60_000)
lists["markdown"] = md
for k, v in lists.items():
    with open(os.path.join(OUT, k + ".list"), "w") as fh:
        fh.write("\n".join(v) + "\n")
    print(k, len(v), "files", round(sum(os.path.getsize(f) for f in v) / 1e6, 2), "MB")
